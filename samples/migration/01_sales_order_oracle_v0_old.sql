-- =============================================================================
-- マイグレーション差分比較体験用サンプル: 販売・受注・在庫管理システム (旧版 v0)
-- 使い方:
--   1. 最新版 DDL (samples/ddl/01_sales_order_oracle.sql) を「sales_order」スキーマにインポートします。
--   2. 本ファイル (旧版 v0) を別スキーマ（例: sales_order_v0）にインポートするか、DBML形式で出力します。
--   3. 「ツール → マイグレーションツール」で旧版と比較すると、以下の差分と移行SQL生成を体験できます：
--      - [テーブル新規追加] TRN_SHIPMENTS (出荷実績テーブルの新設)
--      - [カラム追加・桁数拡張] MST_PARTNERS (CLOSING_DAY 追加、PARTNER_NAME 80→120桁へ拡張)
--      - [カラム追加・型拡張] TRN_ORDERS (CUSTOMER_PO_NO / REQUESTED_DELIV_DATE 追加、REMARKS 200→400桁)
--      - [カラム縮小・再作成判定] MST_ITEMS (UNIT_NAME 20→10桁への縮小、TAX_RATE_TYPE 追加)
-- =============================================================================

CREATE TABLE "MST_DEPARTMENTS" (
  "DEPT_CODE"        VARCHAR2(10)  NOT NULL,
  "DEPT_NAME"        VARCHAR2(100) NOT NULL,
  "PARENT_DEPT_CODE" VARCHAR2(10),
  "MANAGER_NAME"     VARCHAR2(60),
  "ACTIVE_FLAG"      CHAR(1)       DEFAULT '1' NOT NULL,
  "CREATED_AT"       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  "UPDATED_AT"       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT "PK_MST_DEPARTMENTS" PRIMARY KEY ("DEPT_CODE")
    USING INDEX TABLESPACE "APP_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "APP_DATA";

COMMENT ON TABLE  "MST_DEPARTMENTS" IS '部門マスタ';
COMMENT ON COLUMN "MST_DEPARTMENTS"."DEPT_CODE"        IS '部門コード';
COMMENT ON COLUMN "MST_DEPARTMENTS"."DEPT_NAME"        IS '部門名称';
COMMENT ON COLUMN "MST_DEPARTMENTS"."PARENT_DEPT_CODE" IS '上位部門コード';
COMMENT ON COLUMN "MST_DEPARTMENTS"."MANAGER_NAME"     IS '部門責任者名';
COMMENT ON COLUMN "MST_DEPARTMENTS"."ACTIVE_FLAG"      IS '有効フラグ (1:有効 / 0:廃止)';
COMMENT ON COLUMN "MST_DEPARTMENTS"."CREATED_AT"       IS '登録日時';
COMMENT ON COLUMN "MST_DEPARTMENTS"."UPDATED_AT"       IS '更新日時';

