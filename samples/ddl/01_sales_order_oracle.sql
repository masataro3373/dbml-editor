-- 1. 部門マスタ (MST_DEPARTMENTS)
CREATE TABLE "MST_DEPARTMENTS" (
  "DEPT_CODE"        VARCHAR2(10)  NOT NULL,
  "DEPT_NAME"        VARCHAR2(100) NOT NULL,
  "PARENT_DEPT_CODE" VARCHAR2(10),
  "MANAGER_NAME"     VARCHAR2(60),
  "ACTIVE_FLAG"      CHAR(1)       DEFAULT '1' NOT NULL,
  "CREATED_AT"       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  "UPDATED_AT"       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT "PK_MST_DEPARTMENTS" PRIMARY KEY ("DEPT_CODE")
    USING INDEX TABLESPACE "APP_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "APP_DATA";

COMMENT ON TABLE  "MST_DEPARTMENTS" IS '部門マスタ';
COMMENT ON COLUMN "MST_DEPARTMENTS"."DEPT_CODE"        IS '部門コード';
COMMENT ON COLUMN "MST_DEPARTMENTS"."DEPT_NAME"        IS '部門名称';
COMMENT ON COLUMN "MST_DEPARTMENTS"."PARENT_DEPT_CODE" IS '上位部門コード';
COMMENT ON COLUMN "MST_DEPARTMENTS"."MANAGER_NAME"     IS '部門責任者名';
COMMENT ON COLUMN "MST_DEPARTMENTS"."ACTIVE_FLAG"      IS '有効フラグ (1:有効 / 0:廃止)';
COMMENT ON COLUMN "MST_DEPARTMENTS"."CREATED_AT"       IS '登録日時';
COMMENT ON COLUMN "MST_DEPARTMENTS"."UPDATED_AT"       IS '更新日時';

-- 2. 取引先マスタ (MST_PARTNERS)
CREATE TABLE "MST_PARTNERS" (
  "PARTNER_CODE"      VARCHAR2(16)  NOT NULL,
  "PARTNER_NAME"      VARCHAR2(120) NOT NULL,
  "PARTNER_TYPE"      VARCHAR2(10)  DEFAULT 'CUSTOMER' NOT NULL,
  "CREDIT_LIMIT_AMT"  NUMBER(15,2)  DEFAULT 0 NOT NULL,
  "CLOSING_DAY"       NUMBER(2)     DEFAULT 99 NOT NULL,
  "SALES_DEPT_CODE"   VARCHAR2(10)  NOT NULL,
  "POSTAL_CODE"       VARCHAR2(10),
  "ADDRESS"           VARCHAR2(250),
  "PHONE_NUMBER"      VARCHAR2(20),
  "STATUS_CODE"       VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  "CREATED_AT"        TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT "PK_MST_PARTNERS" PRIMARY KEY ("PARTNER_CODE")
    USING INDEX TABLESPACE "APP_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "APP_DATA";

CREATE INDEX "IDX_MST_PARTNERS_DEPT" ON "MST_PARTNERS" ("SALES_DEPT_CODE") TABLESPACE "APP_IDX";

COMMENT ON TABLE  "MST_PARTNERS" IS '取引先マスタ';
COMMENT ON COLUMN "MST_PARTNERS"."PARTNER_CODE"     IS '取引先コード';
COMMENT ON COLUMN "MST_PARTNERS"."PARTNER_NAME"     IS '取引先正式名称';
COMMENT ON COLUMN "MST_PARTNERS"."PARTNER_TYPE"     IS '取引先区分 (CUSTOMER:得意先 / BOTH:双方)';
COMMENT ON COLUMN "MST_PARTNERS"."CREDIT_LIMIT_AMT" IS '与信限度額';
COMMENT ON COLUMN "MST_PARTNERS"."CLOSING_DAY"      IS '請求締日 (99:月末)';
COMMENT ON COLUMN "MST_PARTNERS"."SALES_DEPT_CODE"  IS '担当営業部門コード';
COMMENT ON COLUMN "MST_PARTNERS"."POSTAL_CODE"      IS '郵便番号';
COMMENT ON COLUMN "MST_PARTNERS"."ADDRESS"          IS '所在地住所';
COMMENT ON COLUMN "MST_PARTNERS"."PHONE_NUMBER"     IS '代表電話番号';
COMMENT ON COLUMN "MST_PARTNERS"."STATUS_CODE"      IS '取引状態 (ACTIVE:取引中 / SUSPENDED:停止)';
COMMENT ON COLUMN "MST_PARTNERS"."CREATED_AT"       IS '登録日時';

-- 3. 倉庫マスタ (MST_WAREHOUSES)
CREATE TABLE "MST_WAREHOUSES" (
  "WAREHOUSE_CODE" VARCHAR2(10)  NOT NULL,
  "WAREHOUSE_NAME" VARCHAR2(100) NOT NULL,
  "REGION_CODE"    VARCHAR2(10)  NOT NULL,
  "ADDRESS"        VARCHAR2(250),
  "CAPACITY_VOLUME" NUMBER(12,2),
  "ACTIVE_FLAG"    CHAR(1)       DEFAULT '1' NOT NULL,
  CONSTRAINT "PK_MST_WAREHOUSES" PRIMARY KEY ("WAREHOUSE_CODE")
    USING INDEX TABLESPACE "APP_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "APP_DATA";

COMMENT ON TABLE  "MST_WAREHOUSES" IS '倉庫マスタ';
COMMENT ON COLUMN "MST_WAREHOUSES"."WAREHOUSE_CODE"  IS '倉庫コード';
COMMENT ON COLUMN "MST_WAREHOUSES"."WAREHOUSE_NAME"  IS '倉庫名称';
COMMENT ON COLUMN "MST_WAREHOUSES"."REGION_CODE"     IS '管轄エリアコード';
COMMENT ON COLUMN "MST_WAREHOUSES"."ADDRESS"         IS '倉庫所在地';
COMMENT ON COLUMN "MST_WAREHOUSES"."CAPACITY_VOLUME" IS '最大保管容積(m3)';
COMMENT ON COLUMN "MST_WAREHOUSES"."ACTIVE_FLAG"     IS '稼働フラグ';

-- 4. 商品マスタ (MST_ITEMS)
CREATE TABLE "MST_ITEMS" (
  "ITEM_CODE"          VARCHAR2(20)  NOT NULL,
  "ITEM_NAME"          VARCHAR2(150) NOT NULL,
  "CATEGORY_CODE"      VARCHAR2(15)  NOT NULL,
  "UNIT_NAME"          VARCHAR2(10)  DEFAULT 'PCS' NOT NULL,
  "STANDARD_PRICE"     NUMBER(12,2)  DEFAULT 0 NOT NULL,
  "COST_PRICE"         NUMBER(12,2)  DEFAULT 0 NOT NULL,
  "TAX_RATE_TYPE"      VARCHAR2(10)  DEFAULT 'STANDARD' NOT NULL,
  "SAFETY_STOCK_QTY"   NUMBER(10,2)  DEFAULT 0 NOT NULL,
  "DISCONTINUED_FLAG"  CHAR(1)       DEFAULT '0' NOT NULL,
  "UPDATED_AT"         TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT "PK_MST_ITEMS" PRIMARY KEY ("ITEM_CODE")
    USING INDEX TABLESPACE "APP_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "APP_DATA";

CREATE INDEX "IDX_MST_ITEMS_CATEGORY" ON "MST_ITEMS" ("CATEGORY_CODE") TABLESPACE "APP_IDX";

COMMENT ON TABLE  "MST_ITEMS" IS '商品マスタ';
COMMENT ON COLUMN "MST_ITEMS"."ITEM_CODE"         IS '商品コード';
COMMENT ON COLUMN "MST_ITEMS"."ITEM_NAME"         IS '商品名';
COMMENT ON COLUMN "MST_ITEMS"."CATEGORY_CODE"     IS '商品カテゴリコード';
COMMENT ON COLUMN "MST_ITEMS"."UNIT_NAME"         IS '基本単位 (PCS/BOX/KG)';
COMMENT ON COLUMN "MST_ITEMS"."STANDARD_PRICE"    IS '標準販売単価';
COMMENT ON COLUMN "MST_ITEMS"."COST_PRICE"        IS '標準原価';
COMMENT ON COLUMN "MST_ITEMS"."TAX_RATE_TYPE"     IS '税率区分 (STANDARD:10% / REDUCED:8%)';
COMMENT ON COLUMN "MST_ITEMS"."SAFETY_STOCK_QTY"  IS '安全在庫数量';
COMMENT ON COLUMN "MST_ITEMS"."DISCONTINUED_FLAG" IS '廃番フラグ (0:販売中 / 1:廃番)';
COMMENT ON COLUMN "MST_ITEMS"."UPDATED_AT"        IS '更新日時';

-- 5. 在庫残高テーブル (TRN_INVENTORIES) [倉庫×商品の複合主キー]
CREATE TABLE "TRN_INVENTORIES" (
  "WAREHOUSE_CODE"    VARCHAR2(10) NOT NULL,
  "ITEM_CODE"         VARCHAR2(20) NOT NULL,
  "ON_HAND_QTY"       NUMBER(12,2) DEFAULT 0 NOT NULL,
  "ALLOCATED_QTY"     NUMBER(12,2) DEFAULT 0 NOT NULL,
  "AVAILABLE_QTY"     NUMBER(12,2) DEFAULT 0 NOT NULL,
  "LAST_INBOUND_DATE" DATE,
  "LAST_OUTBOUND_DATE" DATE,
  "UPDATED_AT"        TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT "PK_TRN_INVENTORIES" PRIMARY KEY ("WAREHOUSE_CODE", "ITEM_CODE")
    USING INDEX TABLESPACE "APP_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "APP_DATA";

CREATE INDEX "IDX_TRN_INVENTORIES_ITEM" ON "TRN_INVENTORIES" ("ITEM_CODE") TABLESPACE "APP_IDX";

COMMENT ON TABLE  "TRN_INVENTORIES" IS '在庫残高';
COMMENT ON COLUMN "TRN_INVENTORIES"."WAREHOUSE_CODE"     IS '倉庫コード';
COMMENT ON COLUMN "TRN_INVENTORIES"."ITEM_CODE"          IS '商品コード';
COMMENT ON COLUMN "TRN_INVENTORIES"."ON_HAND_QTY"        IS '現在庫数量';
COMMENT ON COLUMN "TRN_INVENTORIES"."ALLOCATED_QTY"      IS '引当済数量';
COMMENT ON COLUMN "TRN_INVENTORIES"."AVAILABLE_QTY"      IS '有効在庫数量';
COMMENT ON COLUMN "TRN_INVENTORIES"."LAST_INBOUND_DATE"  IS '最終入庫日';
COMMENT ON COLUMN "TRN_INVENTORIES"."LAST_OUTBOUND_DATE" IS '最終出庫日';
COMMENT ON COLUMN "TRN_INVENTORIES"."UPDATED_AT"         IS '更新日時';

-- 6. 受注ヘッダ (TRN_ORDERS)
CREATE TABLE "TRN_ORDERS" (
  "ORDER_NO"            VARCHAR2(20)  NOT NULL,
  "ORDER_DATE"          DATE          NOT NULL,
  "PARTNER_CODE"        VARCHAR2(16)  NOT NULL,
  "SALES_DEPT_CODE"     VARCHAR2(10)  NOT NULL,
  "CUSTOMER_PO_NO"      VARCHAR2(40),
  "REQUESTED_DELIV_DATE" DATE,
  "ORDER_STATUS"        VARCHAR2(15)  DEFAULT 'NEW' NOT NULL,
  "TOTAL_ITEM_AMT"      NUMBER(15,2)  DEFAULT 0 NOT NULL,
  "TOTAL_TAX_AMT"       NUMBER(15,2)  DEFAULT 0 NOT NULL,
  "REMARKS"             VARCHAR2(400),
  "CREATED_AT"          TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  "UPDATED_AT"          TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT "PK_TRN_ORDERS" PRIMARY KEY ("ORDER_NO")
    USING INDEX TABLESPACE "APP_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "APP_DATA";

CREATE INDEX "IDX_TRN_ORDERS_PARTNER" ON "TRN_ORDERS" ("PARTNER_CODE", "ORDER_DATE") TABLESPACE "APP_IDX";
CREATE INDEX "IDX_TRN_ORDERS_DEPT"    ON "TRN_ORDERS" ("SALES_DEPT_CODE") TABLESPACE "APP_IDX";

COMMENT ON TABLE  "TRN_ORDERS" IS '受注ヘッダ';
COMMENT ON COLUMN "TRN_ORDERS"."ORDER_NO"             IS '受注番号';
COMMENT ON COLUMN "TRN_ORDERS"."ORDER_DATE"           IS '受注日';
COMMENT ON COLUMN "TRN_ORDERS"."PARTNER_CODE"         IS '得意先コード';
COMMENT ON COLUMN "TRN_ORDERS"."SALES_DEPT_CODE"      IS '受注部門コード';
COMMENT ON COLUMN "TRN_ORDERS"."CUSTOMER_PO_NO"       IS '客先注文番号';
COMMENT ON COLUMN "TRN_ORDERS"."REQUESTED_DELIV_DATE" IS '希望納期';
COMMENT ON COLUMN "TRN_ORDERS"."ORDER_STATUS"         IS '受注ステータス (NEW:新規 / ALLOCATED:引当済 / SHIPPED:出荷済 / CANCELLED:取消)';
COMMENT ON COLUMN "TRN_ORDERS"."TOTAL_ITEM_AMT"       IS '受注税抜合計金額';
COMMENT ON COLUMN "TRN_ORDERS"."TOTAL_TAX_AMT"        IS '消費税合計額';
COMMENT ON COLUMN "TRN_ORDERS"."REMARKS"              IS '受注備考';
COMMENT ON COLUMN "TRN_ORDERS"."CREATED_AT"           IS '登録日時';
COMMENT ON COLUMN "TRN_ORDERS"."UPDATED_AT"           IS '更新日時';

-- 7. 受注明細 (TRN_ORDER_DETAILS) [受注番号×明細行番号の複合主キー]
CREATE TABLE "TRN_ORDER_DETAILS" (
  "ORDER_NO"       VARCHAR2(20) NOT NULL,
  "LINE_NO"        NUMBER(4)    NOT NULL,
  "ITEM_CODE"      VARCHAR2(20) NOT NULL,
  "WAREHOUSE_CODE" VARCHAR2(10) NOT NULL,
  "ORDER_QTY"      NUMBER(12,2) NOT NULL,
  "UNIT_PRICE"     NUMBER(12,2) NOT NULL,
  "LINE_AMOUNT"    NUMBER(15,2) NOT NULL,
  "SHIPPED_QTY"    NUMBER(12,2) DEFAULT 0 NOT NULL,
  "LINE_STATUS"    VARCHAR2(15) DEFAULT 'OPEN' NOT NULL,
  CONSTRAINT "PK_TRN_ORDER_DETAILS" PRIMARY KEY ("ORDER_NO", "LINE_NO")
    USING INDEX TABLESPACE "APP_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "APP_DATA";

CREATE INDEX "IDX_TRN_ORDER_DETAILS_ITEM" ON "TRN_ORDER_DETAILS" ("ITEM_CODE") TABLESPACE "APP_IDX";

COMMENT ON TABLE  "TRN_ORDER_DETAILS" IS '受注明細';
COMMENT ON COLUMN "TRN_ORDER_DETAILS"."ORDER_NO"       IS '受注番号';
COMMENT ON COLUMN "TRN_ORDER_DETAILS"."LINE_NO"        IS '明細行番号';
COMMENT ON COLUMN "TRN_ORDER_DETAILS"."ITEM_CODE"      IS '商品コード';
COMMENT ON COLUMN "TRN_ORDER_DETAILS"."WAREHOUSE_CODE" IS '引当倉庫コード';
COMMENT ON COLUMN "TRN_ORDER_DETAILS"."ORDER_QTY"      IS '受注数量';
COMMENT ON COLUMN "TRN_ORDER_DETAILS"."UNIT_PRICE"     IS '販売単価';
COMMENT ON COLUMN "TRN_ORDER_DETAILS"."LINE_AMOUNT"    IS '明細金額';
COMMENT ON COLUMN "TRN_ORDER_DETAILS"."SHIPPED_QTY"    IS '出荷済数量';
COMMENT ON COLUMN "TRN_ORDER_DETAILS"."LINE_STATUS"    IS '明細ステータス (OPEN:未出荷 / COMPLETED:出荷完了)';

-- 8. 出荷実績 (TRN_SHIPMENTS)
CREATE TABLE "TRN_SHIPMENTS" (
  "SHIPMENT_NO"     VARCHAR2(20)  NOT NULL,
  "ORDER_NO"        VARCHAR2(20)  NOT NULL,
  "WAREHOUSE_CODE"  VARCHAR2(10)  NOT NULL,
  "SHIP_DATE"       DATE          NOT NULL,
  "CARRIER_NAME"    VARCHAR2(80),
  "TRACKING_NO"     VARCHAR2(50),
  "SHIPMENT_STATUS" VARCHAR2(15)  DEFAULT 'DISPATCHED' NOT NULL,
  "CREATED_AT"      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT "PK_TRN_SHIPMENTS" PRIMARY KEY ("SHIPMENT_NO")
    USING INDEX TABLESPACE "APP_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "APP_DATA";

CREATE INDEX "IDX_TRN_SHIPMENTS_ORDER" ON "TRN_SHIPMENTS" ("ORDER_NO") TABLESPACE "APP_IDX";

COMMENT ON TABLE  "TRN_SHIPMENTS" IS '出荷実績';
COMMENT ON COLUMN "TRN_SHIPMENTS"."SHIPMENT_NO"     IS '出荷番号';
COMMENT ON COLUMN "TRN_SHIPMENTS"."ORDER_NO"        IS '受注番号';
COMMENT ON COLUMN "TRN_SHIPMENTS"."WAREHOUSE_CODE"  IS '出荷元倉庫コード';
COMMENT ON COLUMN "TRN_SHIPMENTS"."SHIP_DATE"       IS '出荷日';
COMMENT ON COLUMN "TRN_SHIPMENTS"."CARRIER_NAME"    IS '配送業者名';
COMMENT ON COLUMN "TRN_SHIPMENTS"."TRACKING_NO"     IS '送り状追跡番号';
COMMENT ON COLUMN "TRN_SHIPMENTS"."SHIPMENT_STATUS" IS '出荷状態 (READY:出荷準備 / DISPATCHED:発送済 / DELIVERED:配達完了)';
COMMENT ON COLUMN "TRN_SHIPMENTS"."CREATED_AT"      IS '登録日時';

