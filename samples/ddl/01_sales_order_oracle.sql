-- =============================================================================
-- サンプルDDL 01: 販売・受注・在庫管理システム (Sales, Order & Inventory Management)
-- 対象DBMS方言 : Oracle (12c+) / Oracle (<= 11g)
-- 推奨スキーマ名: sales_order
-- テーブル数   : 8テーブル (マスタ4 / トランザクション4)
