-- =============================================================================
-- サンプルDDL 02: 生産・製造・BOM・購買管理システム (Manufacturing, BOM & Procurement)
-- 対象DBMS方言 : Oracle (12c+) / Oracle (<= 11g)
-- 推奨スキーマ名: manufacturing_bom
-- テーブル数   : 7テーブル (マスタ4 / トランザクション3)
-- =============================================================================

-- 1. 仕入先マスタ (MST_SUPPLIERS)
CREATE TABLE "MST_SUPPLIERS" (
  "SUPPLIER_CODE"    VARCHAR2(16)  NOT NULL,
  "SUPPLIER_NAME"    VARCHAR2(120) NOT NULL,
  "COUNTRY_CODE"     CHAR(2)       DEFAULT 'JP' NOT NULL,
  "LEAD_TIME_DAYS"   NUMBER(3)     DEFAULT 7 NOT NULL,
  "CONTACT_EMAIL"    VARCHAR2(120),
  "QUALITY_RANK"     CHAR(1)       DEFAULT 'A' NOT NULL,
  "ACTIVE_FLAG"      CHAR(1)       DEFAULT '1' NOT NULL,
  CONSTRAINT "PK_MST_SUPPLIERS" PRIMARY KEY ("SUPPLIER_CODE")
    USING INDEX TABLESPACE "MFG_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "MFG_DATA";

COMMENT ON TABLE  "MST_SUPPLIERS" IS '仕入先マスタ';
COMMENT ON COLUMN "MST_SUPPLIERS"."SUPPLIER_CODE"  IS '仕入先コード';
COMMENT ON COLUMN "MST_SUPPLIERS"."SUPPLIER_NAME"  IS '仕入先名称';
COMMENT ON COLUMN "MST_SUPPLIERS"."COUNTRY_CODE"   IS '国コード (ISO 2文字)';
COMMENT ON COLUMN "MST_SUPPLIERS"."LEAD_TIME_DAYS" IS '標準調達リードタイム(日)';
COMMENT ON COLUMN "MST_SUPPLIERS"."CONTACT_EMAIL"  IS '発注窓口メールアドレス';
COMMENT ON COLUMN "MST_SUPPLIERS"."QUALITY_RANK"   IS '品質評価ランク (S/A/B/C)';
COMMENT ON COLUMN "MST_SUPPLIERS"."ACTIVE_FLAG"    IS '取引有効フラグ';

-- 2. 製造工程マスタ (MST_PROCESSES)
CREATE TABLE "MST_PROCESSES" (
  "PROCESS_CODE"       VARCHAR2(12)  NOT NULL,
  "PROCESS_NAME"       VARCHAR2(100) NOT NULL,
  "WORK_CENTER_CODE"   VARCHAR2(12)  NOT NULL,
  "STANDARD_CYCLE_SEC" NUMBER(8,2)   DEFAULT 60 NOT NULL,
  "HOURLY_RATE_AMT"    NUMBER(10,2)  DEFAULT 0 NOT NULL,
  CONSTRAINT "PK_MST_PROCESSES" PRIMARY KEY ("PROCESS_CODE")
    USING INDEX TABLESPACE "MFG_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "MFG_DATA";

COMMENT ON TABLE  "MST_PROCESSES" IS '製造工程マスタ';
COMMENT ON COLUMN "MST_PROCESSES"."PROCESS_CODE"       IS '工程コード';
COMMENT ON COLUMN "MST_PROCESSES"."PROCESS_NAME"       IS '工程名称';
COMMENT ON COLUMN "MST_PROCESSES"."WORK_CENTER_CODE"   IS '作業区・ラインコード';
COMMENT ON COLUMN "MST_PROCESSES"."STANDARD_CYCLE_SEC" IS '標準サイクルタイム(秒)';
COMMENT ON COLUMN "MST_PROCESSES"."HOURLY_RATE_AMT"    IS '時間あたり加工費単価';

-- 3. 品目・製品マスタ (MST_PRODUCTS)
CREATE TABLE "MST_PRODUCTS" (
  "PRODUCT_CODE"          VARCHAR2(20)  NOT NULL,
  "PRODUCT_NAME"          VARCHAR2(150) NOT NULL,
  "ITEM_TYPE"             VARCHAR2(15)  NOT NULL,
  "UNIT_CODE"             VARCHAR2(10)  DEFAULT 'EA' NOT NULL,
  "PRIMARY_SUPPLIER_CODE" VARCHAR2(16),
  "PRIMARY_PROCESS_CODE"  VARCHAR2(12),
  "STANDARD_LOT_SIZE"     NUMBER(10,2)  DEFAULT 1 NOT NULL,
  "STANDARD_COST"         NUMBER(14,4)  DEFAULT 0 NOT NULL,
  "DRAWING_NO"            VARCHAR2(40),
  "UPDATED_AT"            TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT "PK_MST_PRODUCTS" PRIMARY KEY ("PRODUCT_CODE")
    USING INDEX TABLESPACE "MFG_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "MFG_DATA";

CREATE INDEX "IDX_MST_PRODUCTS_SUPPLIER" ON "MST_PRODUCTS" ("PRIMARY_SUPPLIER_CODE") TABLESPACE "MFG_IDX";

COMMENT ON TABLE  "MST_PRODUCTS" IS '品目・製品マスタ';
COMMENT ON COLUMN "MST_PRODUCTS"."PRODUCT_CODE"          IS '品目コード';
COMMENT ON COLUMN "MST_PRODUCTS"."PRODUCT_NAME"          IS '品目名称';
COMMENT ON COLUMN "MST_PRODUCTS"."ITEM_TYPE"             IS '品目区分 (FINISHED:完成品 / SEMI:半製品 / RAW:原材料)';
COMMENT ON COLUMN "MST_PRODUCTS"."UNIT_CODE"             IS '計量単位 (EA/KG/M)';
COMMENT ON COLUMN "MST_PRODUCTS"."PRIMARY_SUPPLIER_CODE" IS '主仕入先コード';
COMMENT ON COLUMN "MST_PRODUCTS"."PRIMARY_PROCESS_CODE"  IS '主製造工程コード';
COMMENT ON COLUMN "MST_PRODUCTS"."STANDARD_LOT_SIZE"     IS '標準製造ロット数';
COMMENT ON COLUMN "MST_PRODUCTS"."STANDARD_COST"         IS '標準製造原価';
COMMENT ON COLUMN "MST_PRODUCTS"."DRAWING_NO"            IS '設計図面番号';
COMMENT ON COLUMN "MST_PRODUCTS"."UPDATED_AT"            IS '更新日時';

-- 4. 部品構成表・BOMマスタ (MST_BOM_STRUCTURES) [親品目×子品目の自己参照リレーション]
CREATE TABLE "MST_BOM_STRUCTURES" (
  "PARENT_PRODUCT_CODE" VARCHAR2(20) NOT NULL,
  "CHILD_PRODUCT_CODE"  VARCHAR2(20) NOT NULL,
  "REQUIRED_QTY"        NUMBER(12,4) NOT NULL,
  "SCRAP_RATE_PCT"      NUMBER(5,2)  DEFAULT 0 NOT NULL,
  "EFFECTIVE_FROM_DATE" DATE         NOT NULL,
  "EFFECTIVE_TO_DATE"   DATE,
  CONSTRAINT "PK_MST_BOM_STRUCTURES" PRIMARY KEY ("PARENT_PRODUCT_CODE", "CHILD_PRODUCT_CODE")
    USING INDEX TABLESPACE "MFG_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "MFG_DATA";

CREATE INDEX "IDX_MST_BOM_CHILD" ON "MST_BOM_STRUCTURES" ("CHILD_PRODUCT_CODE") TABLESPACE "MFG_IDX";

COMMENT ON TABLE  "MST_BOM_STRUCTURES" IS '部品構成表(BOM)マスタ';
COMMENT ON COLUMN "MST_BOM_STRUCTURES"."PARENT_PRODUCT_CODE" IS '親品目コード';
COMMENT ON COLUMN "MST_BOM_STRUCTURES"."CHILD_PRODUCT_CODE"  IS '子品目(構成部品)コード';
COMMENT ON COLUMN "MST_BOM_STRUCTURES"."REQUIRED_QTY"        IS '員数(親1単位あたり必要数)';
COMMENT ON COLUMN "MST_BOM_STRUCTURES"."SCRAP_RATE_PCT"      IS '標準歩留ロス率(%)';
COMMENT ON COLUMN "MST_BOM_STRUCTURES"."EFFECTIVE_FROM_DATE" IS '設計適用開始日';
COMMENT ON COLUMN "MST_BOM_STRUCTURES"."EFFECTIVE_TO_DATE"   IS '設計適用終了日';

-- 5. 部材発注トラン (TRN_PURCHASE_ORDERS)
CREATE TABLE "TRN_PURCHASE_ORDERS" (
  "PO_NO"          VARCHAR2(20) NOT NULL,
  "SUPPLIER_CODE"  VARCHAR2(16) NOT NULL,
  "PRODUCT_CODE"   VARCHAR2(20) NOT NULL,
  "ORDER_DATE"     DATE         NOT NULL,
  "DUE_DATE"       DATE         NOT NULL,
  "ORDER_QTY"      NUMBER(12,2) NOT NULL,
  "RECEIVED_QTY"   NUMBER(12,2) DEFAULT 0 NOT NULL,
  "UNIT_PRICE"     NUMBER(14,4) NOT NULL,
  "PO_STATUS"      VARCHAR2(15) DEFAULT 'ISSUED' NOT NULL,
  CONSTRAINT "PK_TRN_PURCHASE_ORDERS" PRIMARY KEY ("PO_NO")
    USING INDEX TABLESPACE "MFG_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "MFG_DATA";

CREATE INDEX "IDX_TRN_PO_SUPPLIER" ON "TRN_PURCHASE_ORDERS" ("SUPPLIER_CODE", "DUE_DATE") TABLESPACE "MFG_IDX";

COMMENT ON TABLE  "TRN_PURCHASE_ORDERS" IS '部材発注トラン';
COMMENT ON COLUMN "TRN_PURCHASE_ORDERS"."PO_NO"         IS '発注番号';
COMMENT ON COLUMN "TRN_PURCHASE_ORDERS"."SUPPLIER_CODE" IS '仕入先コード';
COMMENT ON COLUMN "TRN_PURCHASE_ORDERS"."PRODUCT_CODE"  IS '発注品目コード';
COMMENT ON COLUMN "TRN_PURCHASE_ORDERS"."ORDER_DATE"    IS '発注日';
COMMENT ON COLUMN "TRN_PURCHASE_ORDERS"."DUE_DATE"      IS '納入指定日';
COMMENT ON COLUMN "TRN_PURCHASE_ORDERS"."ORDER_QTY"     IS '発注数量';
COMMENT ON COLUMN "TRN_PURCHASE_ORDERS"."RECEIVED_QTY"  IS '受入検収済数量';
COMMENT ON COLUMN "TRN_PURCHASE_ORDERS"."UNIT_PRICE"    IS '発注単価';
COMMENT ON COLUMN "TRN_PURCHASE_ORDERS"."PO_STATUS"     IS '発注ステータス (ISSUED:発注済 / PARTIAL:分納中 / CLOSED:完納)';

-- 6. 製造指示ヘッダ (TRN_WORK_ORDERS)
CREATE TABLE "TRN_WORK_ORDERS" (
  "WORK_ORDER_NO"   VARCHAR2(20) NOT NULL,
  "PRODUCT_CODE"    VARCHAR2(20) NOT NULL,
  "LOT_NO"          VARCHAR2(30) NOT NULL,
  "PLANNED_QTY"     NUMBER(12,2) NOT NULL,
  "COMPLETED_QTY"   NUMBER(12,2) DEFAULT 0 NOT NULL,
  "DEFECT_QTY"      NUMBER(12,2) DEFAULT 0 NOT NULL,
  "PLAN_START_DATE" DATE         NOT NULL,
  "PLAN_END_DATE"   DATE         NOT NULL,
  "WORK_STATUS"     VARCHAR2(15) DEFAULT 'RELEASED' NOT NULL,
  "CREATED_AT"      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT "PK_TRN_WORK_ORDERS" PRIMARY KEY ("WORK_ORDER_NO")
    USING INDEX TABLESPACE "MFG_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "MFG_DATA";

CREATE INDEX "IDX_TRN_WO_PRODUCT" ON "TRN_WORK_ORDERS" ("PRODUCT_CODE", "PLAN_START_DATE") TABLESPACE "MFG_IDX";

COMMENT ON TABLE  "TRN_WORK_ORDERS" IS '製造指示ヘッダ';
COMMENT ON COLUMN "TRN_WORK_ORDERS"."WORK_ORDER_NO"   IS '製造指示番号';
COMMENT ON COLUMN "TRN_WORK_ORDERS"."PRODUCT_CODE"    IS '製造品目コード';
COMMENT ON COLUMN "TRN_WORK_ORDERS"."LOT_NO"          IS '製造ロット番号';
COMMENT ON COLUMN "TRN_WORK_ORDERS"."PLANNED_QTY"     IS '指示数量';
COMMENT ON COLUMN "TRN_WORK_ORDERS"."COMPLETED_QTY"   IS '良品完成数量';
COMMENT ON COLUMN "TRN_WORK_ORDERS"."DEFECT_QTY"      IS '不良品数量';
COMMENT ON COLUMN "TRN_WORK_ORDERS"."PLAN_START_DATE" IS '着手予定日';
COMMENT ON COLUMN "TRN_WORK_ORDERS"."PLAN_END_DATE"   IS '完了予定日';
COMMENT ON COLUMN "TRN_WORK_ORDERS"."WORK_STATUS"     IS '製造状態 (RELEASED:指示済 / IN_PROGRESS:製造中 / COMPLETED:完了)';
COMMENT ON COLUMN "TRN_WORK_ORDERS"."CREATED_AT"      IS '登録日時';

-- 7. 工程別製造実績 (TRN_WORK_RESULTS)
CREATE TABLE "TRN_WORK_RESULTS" (
  "RESULT_ID"       VARCHAR2(24) NOT NULL,
  "WORK_ORDER_NO"   VARCHAR2(20) NOT NULL,
  "PROCESS_CODE"    VARCHAR2(12) NOT NULL,
  "START_TIME"      TIMESTAMP    NOT NULL,
  "END_TIME"        TIMESTAMP,
  "GOOD_QTY"        NUMBER(12,2) DEFAULT 0 NOT NULL,
  "REJECT_QTY"      NUMBER(12,2) DEFAULT 0 NOT NULL,
  "MACHINE_CODE"    VARCHAR2(20),
  "OPERATOR_CODE"   VARCHAR2(20),
  CONSTRAINT "PK_TRN_WORK_RESULTS" PRIMARY KEY ("RESULT_ID")
    USING INDEX TABLESPACE "MFG_IDX"
) PCTFREE 10 INITRANS 2 TABLESPACE "MFG_DATA";

CREATE INDEX "IDX_TRN_WR_WO" ON "TRN_WORK_RESULTS" ("WORK_ORDER_NO", "PROCESS_CODE") TABLESPACE "MFG_IDX";

COMMENT ON TABLE  "TRN_WORK_RESULTS" IS '工程別製造実績';
COMMENT ON COLUMN "TRN_WORK_RESULTS"."RESULT_ID"     IS '製造実績ID';
COMMENT ON COLUMN "TRN_WORK_RESULTS"."WORK_ORDER_NO" IS '製造指示番号';
COMMENT ON COLUMN "TRN_WORK_RESULTS"."PROCESS_CODE"  IS '工程コード';
COMMENT ON COLUMN "TRN_WORK_RESULTS"."START_TIME"    IS '作業開始日時';
COMMENT ON COLUMN "TRN_WORK_RESULTS"."END_TIME"      IS '作業終了日時';
COMMENT ON COLUMN "TRN_WORK_RESULTS"."GOOD_QTY"      IS '工程良品数';
COMMENT ON COLUMN "TRN_WORK_RESULTS"."REJECT_QTY"    IS '工程不良数';
COMMENT ON COLUMN "TRN_WORK_RESULTS"."MACHINE_CODE"  IS '使用設備コード';
COMMENT ON COLUMN "TRN_WORK_RESULTS"."OPERATOR_CODE" IS '作業担当者コード';

-- =============================================================================
-- 外部キー制約定義 (Foreign Keys)
-- =============================================================================
ALTER TABLE "MST_PRODUCTS"
  ADD CONSTRAINT "FK_PROD_SUPPLIER" FOREIGN KEY ("PRIMARY_SUPPLIER_CODE")
  REFERENCES "MST_SUPPLIERS" ("SUPPLIER_CODE");

ALTER TABLE "MST_PRODUCTS"
  ADD CONSTRAINT "FK_PROD_PROCESS" FOREIGN KEY ("PRIMARY_PROCESS_CODE")
  REFERENCES "MST_PROCESSES" ("PROCESS_CODE");

ALTER TABLE "MST_BOM_STRUCTURES"
  ADD CONSTRAINT "FK_BOM_PARENT" FOREIGN KEY ("PARENT_PRODUCT_CODE")
  REFERENCES "MST_PRODUCTS" ("PRODUCT_CODE");

ALTER TABLE "MST_BOM_STRUCTURES"
  ADD CONSTRAINT "FK_BOM_CHILD" FOREIGN KEY ("CHILD_PRODUCT_CODE")
  REFERENCES "MST_PRODUCTS" ("PRODUCT_CODE");

ALTER TABLE "TRN_PURCHASE_ORDERS"
  ADD CONSTRAINT "FK_PO_SUPPLIER" FOREIGN KEY ("SUPPLIER_CODE")
  REFERENCES "MST_SUPPLIERS" ("SUPPLIER_CODE");

ALTER TABLE "TRN_PURCHASE_ORDERS"
  ADD CONSTRAINT "FK_PO_PRODUCT" FOREIGN KEY ("PRODUCT_CODE")
  REFERENCES "MST_PRODUCTS" ("PRODUCT_CODE");

ALTER TABLE "TRN_WORK_ORDERS"
  ADD CONSTRAINT "FK_WO_PRODUCT" FOREIGN KEY ("PRODUCT_CODE")
  REFERENCES "MST_PRODUCTS" ("PRODUCT_CODE");

ALTER TABLE "TRN_WORK_RESULTS"
  ADD CONSTRAINT "FK_WR_WO" FOREIGN KEY ("WORK_ORDER_NO")
  REFERENCES "TRN_WORK_ORDERS" ("WORK_ORDER_NO");

ALTER TABLE "TRN_WORK_RESULTS"
  ADD CONSTRAINT "FK_WR_PROCESS" FOREIGN KEY ("PROCESS_CODE")
  REFERENCES "MST_PROCESSES" ("PROCESS_CODE");
